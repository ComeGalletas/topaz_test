-- SQL portable entre H2 (modo PostgreSQL) y PostgreSQL.
create table support_orders (
    id                 bigint generated by default as identity primary key,
    external_reference varchar(50)              not null,
    customer_id        varchar(50)              not null,
    category           varchar(30)              not null,
    description        varchar(500)             not null,
    channel            varchar(30)              not null,
    priority           varchar(10)              not null,
    status             varchar(20)              not null,
    -- Igual a external_reference mientras la orden está activa (OPEN / IN_PROGRESS), NULL en estados finales.
    -- UNIQUE admite múltiples NULL, así que solo puede existir una orden activa por referencia externa.
    active_reference   varchar(50),
    created_at         timestamp with time zone not null,
    updated_at         timestamp with time zone not null,
    version            bigint                   not null default 0,

    constraint uq_support_orders_active_reference unique (active_reference),
    constraint ck_support_orders_category check (category in ('PAYMENT', 'ACCOUNT', 'TECHNICAL', 'SERVICE', 'OTHER')),
    constraint ck_support_orders_channel check (channel in ('MOBILE_APP', 'WEB', 'CALL_CENTER', 'EMAIL')),
    constraint ck_support_orders_priority check (priority in ('LOW', 'MEDIUM', 'HIGH')),
    constraint ck_support_orders_status check (status in ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CANCELLED')),
    constraint ck_support_orders_active_reference check (
        (status in ('OPEN', 'IN_PROGRESS') and active_reference = external_reference)
        or (status in ('RESOLVED', 'CANCELLED') and active_reference is null)
    ),
    constraint ck_support_orders_description_length check (char_length(description) between 10 and 500)
);

-- Listado por estado ordenado por fecha (filtro del operador)
create index ix_support_orders_status_created_at on support_orders (status, created_at desc);
-- Búsqueda del historial de una referencia externa
create index ix_support_orders_external_reference on support_orders (external_reference);
